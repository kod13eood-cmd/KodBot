    fun t(language: AppLanguage, english: String): String {
        if (language == AppLanguage.EN) return english
        MAP[english]?.let { return it }
        for (rule in RULES) {
            val match = rule.first.matchEntire(english) ?: continue
            return rule.second(match)
        }
        return english
    }

