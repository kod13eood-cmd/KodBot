/** The app language follows the phone on first run and can be changed in Settings. */
enum class AppLanguage { EN, BG }

val LocalAppLanguage = staticCompositionLocalOf { AppLanguage.EN }

/** Translate a UI string. English is the source language, so a missing
 * translation falls back to readable English rather than an identifier. */
@Composable
fun tr(english: String): String = AppStrings.t(LocalAppLanguage.current, english)

