/** Persisted language choice. An unset value follows the phone's language. */
object LanguageStore {
    private const val PREFS = "kodbot.locale"
    private const val KEY = "language"

    fun load(context: Context): AppLanguage {
        val stored = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).getString(KEY, null)
        if (stored == "bg") return AppLanguage.BG
        if (stored == "en") return AppLanguage.EN
        return if (java.util.Locale.getDefault().language == "bg") AppLanguage.BG else AppLanguage.EN
    }

    fun save(context: Context, language: AppLanguage) {
        val value = if (language == AppLanguage.BG) "bg" else "en"
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit().putString(KEY, value).apply()
    }
}
